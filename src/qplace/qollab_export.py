"""Export one validated M3 instance and its locally trained QAOA parameters for the Qollab demo.

The demo (``qollab/``) cannot import this package in the browser, so it receives
plain data: qubit map, Ising coefficients, integer capacity data, classical
baselines and the trained angles. ``check_placement_data`` re-derives the file
from the committed artifacts so the two can never drift silently.
"""

from __future__ import annotations

import json
import pprint
from pathlib import Path
from typing import Any

from qplace.quantum_experiment import QuantumExperiment, run_experiment
from qplace.quantum_qaoa import hamiltonian_scale

HEADER = '''"""GENERATED by scripts/generate_m3_artifacts.py from {fixture} -- do not edit.

Synthetic M2 placement instance, its exhaustively validated QUBO/Ising model,
classical baselines (greedy and exact, computed by the qplace repository) and
QAOA angles trained locally with exact statevector simulation.
"""

'''


def build_demo_data(exp: QuantumExperiment, reps: int, gammas: list[float], betas: list[float]) -> dict[str, Any]:
    f, rep = exp.formulation, exp.report
    if f.ising is None or exp.evidence is None or not exp.evidence.valid:
        raise ValueError("demo instance must have a validated formulation")
    return {
        "fixture": exp.fixture,
        "snapshot_sha256": exp.problem.provenance["source_sha256"],
        "target_node": exp.problem.target_node,
        "candidates": [c.pod for c in exp.problem.candidates],
        "destinations": [d.node for d in exp.problem.usable_destinations],
        "num_qubits": f.ising.num_qubits,
        "assignment_qubits": [[p, n] for p, n in f.assignment_vars],
        "slack_qubits": len(f.slack_owner),
        "h": {str(i): float(c) for i, c in sorted(f.ising.h.items())},
        "J": {f"{i},{j}": float(c) for (i, j), c in sorted(f.ising.J.items())},
        "scale": hamiltonian_scale(f.ising),
        "capacity": [[node, res, cap, [[v, a] for v, a in terms]] for node, res, cap, terms in f.capacity_data],
        "classical": {
            "greedy_placed": len(rep.greedy.result.assignments),
            "greedy_assignments": [[a.pod, a.node] for a in rep.greedy.result.assignments],
            "exact_placed": len(rep.exact.result.assignments),
            "exact_assignments": [[a.pod, a.node] for a in rep.exact.result.assignments],
            "m2_assessment": str(rep.assessment),
        },
        "qaoa": {"reps": reps, "gamma": gammas, "beta": betas,
                 "trained_with": "local exact statevector expectation + COBYLA (qplace.quantum_qaoa)"},
    }


def render(data: dict[str, Any]) -> str:
    return HEADER.format(fixture=data["fixture"]) + "DATA = " + pprint.pformat(data, width=100, sort_dicts=True) + "\n"


def write_placement_data(exp: QuantumExperiment, reps: int, path: Path) -> None:
    run = next(r for r in exp.reps_runs if r.reps == reps)
    path.write_text(render(build_demo_data(exp, reps, run.training.gammas, run.training.betas)), encoding="utf-8")


def check_placement_data(path: Path, artifact_dir: Path, reps: int) -> bool:
    from qplace import build_cluster_model, load_snapshot
    from qplace.snapshot import load_snapshot as _ls  # noqa: F401

    root = artifact_dir.parent.parent.parent
    fixture = artifact_dir.name
    snap = next((root / "fixtures").glob(f"*/{fixture}.json"))
    experiment = json.loads((artifact_dir / "qaoa_experiment.json").read_text(encoding="utf-8"))
    run = next(r for r in experiment["runs"] if r["reps"] == reps)
    exp = run_experiment(fixture, build_cluster_model(load_snapshot(snap)), reps_list=())
    expected = render(build_demo_data(exp, reps, run["final_parameters"]["gamma"], run["final_parameters"]["beta"]))
    return path.exists() and path.read_text(encoding="utf-8") == expected
